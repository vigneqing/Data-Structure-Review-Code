/* ═══════════════════════════════════════════════════════════════════
 * 并查集 (Union-Find Sets)
 *
 * 核心思想：用树（双亲表示法）存储集合，每棵树代表一个集合，根结点代表该集合。
 *   S[i] < 0  → i 是根结点，|S[i]| = 该集合的元素个数
 *   S[i] ≥ 0  → S[i] 是结点 i 的父结点
 * ═══════════════════════════════════════════════════════════════════ */

#define SIZE 13
int UFSets[SIZE];       //并查集数组

/* ─────────────────────────────────────────
 * 一、初始化
 * ───────────────────────────────────────── */

//每个元素各自构成一个独立集合，根结点存 -1
void Initial(int S[]){
    for(int i = 0;i<SIZE;i++)
        S[i]=-1;
}

/* ─────────────────────────────────────────
 * 二、Find 查操作（基础版）
 * ───────────────────────────────────────── */

//查：沿父指针不断向上，找到 x 所属集合的根结点并返回
int Find(int S[],int x){
    while(S[x]>=0)              //S[x]≥0 说明 x 还不是根，继续向上找
        x=S[x];
    return x;
}

/* ─────────────────────────────────────────
 * 三、Union 并操作（基础版）
 * ───────────────────────────────────────── */

//并：将 Root2 所在集合合并到 Root1 所在集合（Root2 挂到 Root1 下）
void Union(int S[],int Root1,int Root2){
    //同一集合无需合并
    if(Root1==Root2) return;
    //将Root2所属集合合并到Root1所属集合
    S[Root2]=Root1;
}

/* ─────────────────────────────────────────
 * 四、Union 优化：小树合并大树
 * ───────────────────────────────────────── */

//优化原理：根结点存负数（-元素个数），把小树挂到大树上，避免树退化成单链表
void Union(int S[],int Root1,int Root2){
    if(Root1==Root2) return;
    if(S[Root2]>S[Root1]){      //都是负数：S[Root2]>S[Root1] → Root2 的集合更小
        S[Root1]+=S[Root2];     //累加结点总数（两个负数相加）
        S[Root2]=Root1;         //小树合并到大树上
    }else{
        S[Root2]+=S[Root1];     //累加结点总数（两个负数相加）
        S[Root1]=Root2;         //小树合并到大树上
    }
}

/* ─────────────────────────────────────────
 * 五、Find 优化：路径压缩
 * ───────────────────────────────────────── */

//优化原理：先找到根，再把查找路径上的所有结点直接挂到根下，压缩树的高度
int Find(int S[],int x){
    int root = x;
    while(S[root]>=0)  root=S[root];    //第一遍循环：找到根结点 root
    //第二遍循环：路径压缩
    while(x!=root){
        int temp=S[x];                  //temp 暂存 x 的父结点
        S[x]=root;                      //把 x 直接挂在根结点下
        x=temp;                         //继续处理 x 原来的父结点
    }
    return root;
}
